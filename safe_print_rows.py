"""Isolated synthetic-only row resizing experiment; never connected to production.

This accepts ONLY exact ZIP-member content generated by synthetic_workbook(). It
is not a general XLSX editor. No filesystem destination or publishing API exists.
The total is a literal fixture label, not a calculated financial total.
"""
from dataclasses import dataclass
from datetime import datetime
from hashlib import sha256
from io import BytesIO
from pathlib import Path
from tempfile import TemporaryDirectory
from zipfile import BadZipFile, ZipFile

from openpyxl import Workbook, load_workbook
from openpyxl.styles import Border, Font, Side


class UnsafeWorkbook(ValueError):
    """The input is outside the single, exact synthetic fixture family."""


@dataclass(frozen=True)
class Plan:
    source_hash: str
    old_blank_rows: int
    new_blank_rows: int
    last_data_row: int
    old_total_row: int
    new_total_row: int


def _count(value):
    if type(value) is not int or not 1 <= value <= 5:
        raise UnsafeWorkbook('blank row count must be an integer from 1 to 5')
    return value


def synthetic_workbook(blank_rows=2):
    """Create the only supported fictional template, as bytes, without formulas."""
    n = _count(blank_rows)
    wb = Workbook()
    wb.properties.created = wb.properties.modified = datetime(2000, 1, 1)
    ws = wb.active
    ws.title = 'Synthetic'
    ws.merge_cells('A1:B1')
    ws['A1'] = 'Synthetic fixture'
    ws['A2'], ws['B2'] = 'Item', 'Value'
    ws['A3'], ws['B3'] = 'Example', 1
    total = 4 + n
    ws.merge_cells(start_row=total, start_column=1, end_row=total, end_column=2)
    ws.cell(total, 1, 'Total (literal)')
    line = Side(style='thin', color='FF000000')
    for row in ws.iter_rows(min_row=2, max_row=total, min_col=1, max_col=2):
        for cell in row:
            cell.font = Font(name='Arial', size=10)
            cell.border = Border(left=line, right=line, top=line, bottom=line)
    out = BytesIO()
    wb.save(out)
    return out.getvalue()


def _members(data):
    if not isinstance(data, bytes) or len(data) > 1_000_000:
        raise UnsafeWorkbook('expected a small immutable XLSX byte string')
    try:
        with ZipFile(BytesIO(data)) as z:
            names = z.namelist()
            if len(names) != len(set(names)) or len(names) > 30:
                raise UnsafeWorkbook('unsupported ZIP structure')
            if sum(i.file_size for i in z.infolist()) > 2_000_000:
                raise UnsafeWorkbook('expanded XLSX too large')
            return {name: z.read(name) for name in names}
    except (BadZipFile, OSError, KeyError, RuntimeError) as exc:
        raise UnsafeWorkbook('invalid XLSX') from exc


def plan_rows(source, new_blank_rows):
    """Read-only plan: reject every workbook outside the exact fixture family."""
    new = _count(new_blank_rows)
    members = _members(source)
    for old in range(1, 6):
        if members == _members(synthetic_workbook(old)):
            return Plan(sha256(source).hexdigest(), old, new, 3, 4 + old, 4 + new)
    raise UnsafeWorkbook('not an exact synthetic fixture; all other structures refused')


def apply_plan(source, plan):
    """Return verified bytes from a temporary copy; never modify or publish source.

    Reconstructing this exact synthetic fixture avoids openpyxl's row-move
    semantics entirely. A changed source or forged/stale plan is rejected.
    """
    if not isinstance(plan, Plan) or plan_rows(source, plan.new_blank_rows) != plan:
        raise UnsafeWorkbook('stale or invalid plan')
    with TemporaryDirectory(prefix='safe-print-rows-') as directory:
        source_copy = Path(directory) / 'source.xlsx'
        candidate = Path(directory) / 'candidate.xlsx'
        source_copy.write_bytes(source)
        candidate.write_bytes(synthetic_workbook(plan.new_blank_rows))
        result = candidate.read_bytes()
        if source_copy.read_bytes() != source:
            raise UnsafeWorkbook('temporary source copy changed')
        if _members(result) != _members(synthetic_workbook(plan.new_blank_rows)):
            raise UnsafeWorkbook('candidate verification failed')
        try:
            wb = load_workbook(BytesIO(result), data_only=False)
            ws = wb['Synthetic']
            if (wb.sheetnames != ['Synthetic'] or ws['A3'].value != 'Example'
                    or ws['B3'].value != 1
                    or ws.cell(plan.new_total_row, 1).value != 'Total (literal)'
                    or any(c.data_type == 'f' for row in ws for c in row)
                    or {str(r) for r in ws.merged_cells.ranges}
                    != {'A1:B1', f'A{plan.new_total_row}:B{plan.new_total_row}'}):
                raise UnsafeWorkbook('candidate semantic verification failed')
        finally:
            if 'wb' in locals():
                wb.close()
        return result
